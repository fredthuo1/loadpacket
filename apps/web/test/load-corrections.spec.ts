import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('real API correction, unassignment, stale conflict recovery and cancellation UI', async ({ page, request }) => {
  const base = 'http://127.0.0.1:3102/api/v1';
  const headers = { authorization: 'Bearer ratecon-browser-owner' };
  const created = await request.post(`${base}/loads/manual`, { headers, data: { loadNumber: `B1B-BROWSER-${randomUUID()}`, brokerName: 'Synthetic Broker', equipment: 'Dry Van', totalRate: '1200.00', pickup: { facilityName: 'Synthetic pickup', address: '1 Test Road' }, delivery: { facilityName: 'Synthetic delivery', address: '2 Test Road' }, requirements: [{ documentType: 'BOL', requirement: 'REQUIRED' }, { documentType: 'POD', requirement: 'REQUIRED' }, { documentType: 'CARRIER_INVOICE', requirement: 'REQUIRED' }] } });
  expect(created.status()).toBe(201);
  const { load } = await created.json();
  const management = async () => { const response = await request.get(`${base}/loads/${load.id}/management`, { headers }); expect(response.ok()).toBeTruthy(); return response.json(); };
  const state = await management();
  const assigned = await request.post(`${base}/loads/${load.id}/assign-driver`, { headers, data: { driverId: '00000000-0000-4000-8000-000000000020', expectedToken: state.token, idempotencyKey: randomUUID(), reason: 'Initial browser assignment' } });
  expect(assigned.ok()).toBeTruthy();
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('owner@example.com');
  await page.getByLabel('Password', { exact: true }).fill('local-fixture-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible();
  await page.route('**/api/v1/**', async route => {
    const url = new URL(route.request().url());
    if (!/^\/api\/v1\/(loads(?:\/|$)|owner\/loads\/|back-office\/loads\/|autopilot\/loads\/|money-opportunities\/)/.test(url.pathname)) return route.continue();
    url.port = '3102';
    await route.continue({ url: url.href, headers: { ...route.request().headers(), ...headers } });
  });
  await page.goto(`/loads/${load.id}`);
  await expect(page.getByRole('button', { name: 'Correct load', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Cancel load', exact: true }).click();
  await expect(page.getByRole('alert').filter({hasText:'Enter a reason'})).toBeVisible();
  await page.getByLabel('Change reason').fill('Reviewed pickup correction');
  await page.getByRole('button', { name: 'Correct load', exact: true }).click();
  await page.getByLabel('Pickup Appointment', { exact: true }).fill('Tomorrow 10:00');
  await page.getByLabel('Equipment', { exact: true }).fill('Reefer');
  await page.getByLabel('Payment terms (days)', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Save corrections' }).click();
  await expect(page.getByRole('status')).toContainText('Load corrected.');
  expect((await management()).load.paymentTermsDays).toBe(0);
  await expect(page.getByText('Reviewed pickup correction', { exact: true })).toBeVisible();
  await page.getByLabel('Change reason').fill('Driver no longer available');
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Unassign Driver', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Driver unassigned.');
  await expect(page.getByRole('button', { name: 'Unassign Driver', exact: true })).toBeDisabled();
  const latest = await management();
  // Hold this real API snapshot while testing a stale client. Parent refreshes
  // otherwise sometimes fetch the external change before the action is sent.
  const managementPath = `**/api/v1/loads/${load.id}/management`;
  await page.route(managementPath, route=>route.fulfill({json:latest}));
  await page.getByRole('button',{name:'Refresh management options'}).click();
  const external = await request.post(`${base}/loads/${load.id}/correct`, { headers, data: { expectedToken: latest.token, idempotencyKey: randomUUID(), reason: 'Concurrent dispatcher change', equipment: 'Flatbed' } });
  expect(external.status()).toBe(200);
  await page.getByLabel('Change reason').fill('Broker cancelled shipment');
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Cancel load', exact: true }).click();
  await expect(page.getByRole('alert').filter({hasText:'The load changed'})).toBeVisible();
  await page.unroute(managementPath);
  await page.getByRole('button', { name: 'Refresh management options' }).click();
  await expect(page.getByText('Concurrent dispatcher change', { exact: true })).toBeVisible();
  page.once('dialog', d => d.dismiss());
  await page.getByRole('button', { name: 'Cancel load', exact: true }).click();
  expect((await management()).eligibility.cancel).toBe(true);
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Cancel load', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Load cancelled.');
  await expect(page.getByText('Cancelled — document and assignment history retained')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Correct load', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Cancel load', exact: true })).toBeDisabled();
  const final = await management();
  expect(final.history.filter((e: { type: string }) => e.type === 'LOAD_CANCELLED')).toHaveLength(1);
});
